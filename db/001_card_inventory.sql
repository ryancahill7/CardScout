-- CardScout inventory: cards I own, identified from photos by CardScout.Api.
CREATE TABLE CARD_INVENTORY (
    ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PLAYER           VARCHAR2(200),
    CARD_YEAR        NUMBER(4),
    MANUFACTURER     VARCHAR2(100),
    SET_NAME         VARCHAR2(200),
    CARD_NUMBER      VARCHAR2(50),
    PARALLEL         VARCHAR2(200),
    SERIAL_NUMBER    VARCHAR2(50),
    IS_ROOKIE        CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_ROOKIE IN ('Y', 'N')),
    IS_AUTOGRAPH     CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_AUTOGRAPH IN ('Y', 'N')),
    IS_RELIC         CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_RELIC IN ('Y', 'N')),
    GRADING_COMPANY  VARCHAR2(20),
    GRADE            NUMBER(3,1),
    CONDITION_NOTES  VARCHAR2(2000),
    AI_CONFIDENCE    NUMBER(4,3),
    EBAY_TITLE       VARCHAR2(80) NOT NULL,
    SUGGESTED_PRICE  NUMBER(10,2),
    COMP_PRODUCT_ID  VARCHAR2(50),
    COST_BASIS       NUMBER(10,2),
    STATUS           VARCHAR2(10) DEFAULT 'UNLISTED' NOT NULL
                     CONSTRAINT CK_CARD_INVENTORY_STATUS CHECK (STATUS IN ('UNLISTED', 'LISTED', 'SOLD')),
    LISTED_PRICE     NUMBER(10,2),
    SOLD_PRICE       NUMBER(10,2),
    SOLD_AT          TIMESTAMP,
    FRONT_IMAGE_PATH VARCHAR2(500),
    BACK_IMAGE_PATH  VARCHAR2(500),
    AI_RAW_JSON      CLOB,
    CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_CARD_INVENTORY_STATUS ON CARD_INVENTORY (STATUS, CREATED_AT);
