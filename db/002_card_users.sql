-- Multi-user support: every inventory row belongs to a CARD_USERS row.
--
-- Today a user authenticates with a personal API key (only its SHA-256 hash is stored).
-- AUTH_PROVIDER/AUTH_SUBJECT are for a real identity provider later (e.g. Sign in with Apple,
-- Auth0, Entra): the API would look the user up by the token's issuer + subject instead.
CREATE TABLE CARD_USERS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL          VARCHAR2(320),
    DISPLAY_NAME   VARCHAR2(200),
    API_KEY_HASH   VARCHAR2(64),
    AUTH_PROVIDER  VARCHAR2(50),
    AUTH_SUBJECT   VARCHAR2(200),
    IS_ACTIVE      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
    CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CARD_USERS_API_KEY_HASH UNIQUE (API_KEY_HASH),
    CONSTRAINT UQ_CARD_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UQ_CARD_USERS_AUTH UNIQUE (AUTH_PROVIDER, AUTH_SUBJECT)
);

-- CARD_INVENTORY was empty when this ran, so USER_ID can be NOT NULL straight away
ALTER TABLE CARD_INVENTORY ADD (
    USER_ID NUMBER NOT NULL CONSTRAINT FK_CARD_INVENTORY_USER REFERENCES CARD_USERS (ID)
);

DROP INDEX IX_CARD_INVENTORY_STATUS;
CREATE INDEX IX_CARD_INVENTORY_USER_STATUS ON CARD_INVENTORY (USER_ID, STATUS, CREATED_AT);
