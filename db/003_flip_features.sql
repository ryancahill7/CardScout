-- Flipper features: per-user eBay watchlists with profit alerts, push tokens,
-- portfolio price history, and the extra cost fields needed for real P&L.

-- A saved eBay search. The WatchlistWorker runs it every few minutes, prices each new
-- listing against SportsCardsPro and alerts the user when one clears their thresholds.
CREATE TABLE CARD_WATCHLISTS (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL CONSTRAINT FK_CARD_WATCHLISTS_USER REFERENCES CARD_USERS (ID),
    NAME            VARCHAR2(100) NOT NULL,
    QUERY           VARCHAR2(200) NOT NULL,
    LISTING_TYPE    VARCHAR2(12) DEFAULT 'ANY' NOT NULL
                    CONSTRAINT CK_CARD_WATCHLISTS_TYPE CHECK (LISTING_TYPE IN ('ANY', 'AUCTION', 'FIXED_PRICE')),
    MAX_PRICE       NUMBER(10,2),
    MIN_PROFIT      NUMBER(10,2) DEFAULT 5 NOT NULL,
    MIN_PROFIT_PCT  NUMBER(6,2) DEFAULT 20 NOT NULL,
    GRADED_ONLY     CHAR(1) DEFAULT 'N' NOT NULL CHECK (GRADED_ONLY IN ('Y', 'N')),
    NOTIFY          CHAR(1) DEFAULT 'Y' NOT NULL CHECK (NOTIFY IN ('Y', 'N')),
    IS_ACTIVE       CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y', 'N')),
    LAST_RUN_AT     TIMESTAMP,
    CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_CARD_WATCHLISTS_USER ON CARD_WATCHLISTS (USER_ID, IS_ACTIVE);

-- Every listing a watchlist has evaluated (so it's only priced once), profitable or not.
CREATE TABLE WATCHLIST_HITS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    WATCHLIST_ID      NUMBER NOT NULL CONSTRAINT FK_WATCHLIST_HITS_LIST REFERENCES CARD_WATCHLISTS (ID) ON DELETE CASCADE,
    USER_ID           NUMBER NOT NULL CONSTRAINT FK_WATCHLIST_HITS_USER REFERENCES CARD_USERS (ID),
    ITEM_ID           VARCHAR2(100) NOT NULL,
    TITLE             VARCHAR2(300) NOT NULL,
    LISTING_TYPE      VARCHAR2(12),
    PRICE             NUMBER(10,2) NOT NULL,
    SHIPPING_COST     NUMBER(10,2),
    SHIPPING_ESTIMATED CHAR(1) DEFAULT 'N' NOT NULL CHECK (SHIPPING_ESTIMATED IN ('Y', 'N')),
    END_TIME          TIMESTAMP,
    LISTING_URL       VARCHAR2(1000),
    IMAGE_URL         VARCHAR2(1000),
    COMP_PRODUCT_ID   VARCHAR2(50),
    COMP_PRODUCT_NAME VARCHAR2(300),
    COMP_SET_NAME     VARCHAR2(300),
    COMP_PRICE        NUMBER(10,2),
    COMP_TIER         VARCHAR2(10),
    MATCH_CONFIDENCE  NUMBER(4,3),
    NET_PROFIT        NUMBER(10,2),
    NET_PROFIT_PCT    NUMBER(9,2),
    MAX_BUY_PRICE     NUMBER(10,2),
    IS_PROFITABLE     CHAR(1) DEFAULT 'N' NOT NULL CHECK (IS_PROFITABLE IN ('Y', 'N')),
    USER_STATUS       VARCHAR2(10) DEFAULT 'NEW' NOT NULL
                      CONSTRAINT CK_WATCHLIST_HITS_STATUS CHECK (USER_STATUS IN ('NEW', 'SAVED', 'DISMISSED', 'BOUGHT')),
    NOTIFIED_AT       TIMESTAMP,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_WATCHLIST_HITS_ITEM UNIQUE (WATCHLIST_ID, ITEM_ID)
);

CREATE INDEX IX_WATCHLIST_HITS_USER ON WATCHLIST_HITS (USER_ID, IS_PROFITABLE, CREATED_AT);

-- Expo push tokens, one row per device
CREATE TABLE CARD_PUSH_TOKENS (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID      NUMBER NOT NULL CONSTRAINT FK_CARD_PUSH_TOKENS_USER REFERENCES CARD_USERS (ID),
    TOKEN        VARCHAR2(200) NOT NULL,
    PLATFORM     VARCHAR2(20),
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_SEEN_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CARD_PUSH_TOKENS_TOKEN UNIQUE (TOKEN)
);

CREATE INDEX IX_CARD_PUSH_TOKENS_USER ON CARD_PUSH_TOKENS (USER_ID);

-- Market price snapshots for cards a user holds (PortfolioPriceWorker), for trends and move alerts
CREATE TABLE CARD_PRICE_HISTORY (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID      NUMBER NOT NULL CONSTRAINT FK_CARD_PRICE_HISTORY_USER REFERENCES CARD_USERS (ID),
    INVENTORY_ID NUMBER NOT NULL CONSTRAINT FK_CARD_PRICE_HISTORY_CARD REFERENCES CARD_INVENTORY (ID) ON DELETE CASCADE,
    PRICE        NUMBER(10,2) NOT NULL,
    CAPTURED_AT  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_CARD_PRICE_HISTORY_CARD ON CARD_PRICE_HISTORY (USER_ID, INVENTORY_ID, CAPTURED_AT);

-- Real P&L needs every cost, not just the purchase price. MARKET_PRICE is the latest
-- comp from the price worker, kept apart from SUGGESTED_PRICE (which the user owns).
ALTER TABLE CARD_INVENTORY ADD (
    PURCHASE_SOURCE    VARCHAR2(100),
    PURCHASED_AT       TIMESTAMP,
    GRADING_COST       NUMBER(10,2),
    SALE_SHIPPING_COST NUMBER(10,2),
    MARKET_PRICE       NUMBER(10,2),
    MARKET_PRICE_AT    TIMESTAMP
);
