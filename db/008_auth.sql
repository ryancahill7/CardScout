-- Real sign-in: email + password, federated identities (Apple, Google, eBay, OIDC SSO),
-- rotating refresh tokens, password resets and the browser hand-off for brokered sign-in.
-- Personal API keys (CARD_USERS.API_KEY_HASH) keep working alongside all of this.
--
-- Only new nullable columns on CARD_USERS: existing users' rows are not changed.
-- All timestamps in these tables and columns are UTC (SYS_EXTRACT_UTC(SYSTIMESTAMP)), so
-- expiry checks don't depend on the database or session time zone.

ALTER TABLE CARD_USERS ADD (
    -- ASP.NET Core Identity PasswordHasher v3 format (PBKDF2-HMAC-SHA512, salted); null = no password
    PASSWORD_HASH       VARCHAR2(400),
    -- 'Y' once the user proved they own EMAIL (a provider said so, or they used a reset link)
    EMAIL_VERIFIED      CHAR(1) CONSTRAINT CK_CARD_USERS_EMAIL_VERIFIED CHECK (EMAIL_VERIFIED IN ('Y', 'N')),
    FAILED_LOGIN_COUNT  NUMBER(5),
    LOCKOUT_UNTIL       TIMESTAMP,
    PASSWORD_CHANGED_AT TIMESTAMP,
    LAST_LOGIN_AT       TIMESTAMP
);

-- Emails are stored lowercased by the API; this also stops two rows differing only by case
CREATE UNIQUE INDEX UX_CARD_USERS_EMAIL_LOWER ON CARD_USERS (LOWER(EMAIL));

-- One row per external login linked to a user. PROVIDER is google / apple / ebay / oidc;
-- for oidc, SUBJECT is "{issuer}#{sub}" so two SSO authorities can't collide.
CREATE TABLE CARD_USER_IDENTITIES (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL CONSTRAINT FK_CARD_USER_IDENTITIES_USER REFERENCES CARD_USERS (ID),
    PROVIDER        VARCHAR2(30) NOT NULL,
    SUBJECT         VARCHAR2(600) NOT NULL,
    EMAIL           VARCHAR2(320),
    EMAIL_VERIFIED  CHAR(1) DEFAULT 'N' NOT NULL CHECK (EMAIL_VERIFIED IN ('Y', 'N')),
    CREATED_AT      TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    LAST_USED_AT    TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT UQ_CARD_USER_IDENTITIES UNIQUE (PROVIDER, SUBJECT)
);

CREATE INDEX IX_CARD_USER_IDENTITIES_USER ON CARD_USER_IDENTITIES (USER_ID);

-- Refresh tokens, stored as SHA-256 hashes. Each refresh rotates the token: the old row gets
-- USED_AT and a new row joins the same FAMILY_ID. Presenting a used token again means it
-- leaked, so the whole family (that sign-in session) is revoked.
CREATE TABLE CARD_REFRESH_TOKENS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID        NUMBER NOT NULL CONSTRAINT FK_CARD_REFRESH_TOKENS_USER REFERENCES CARD_USERS (ID),
    TOKEN_HASH     VARCHAR2(64) NOT NULL,
    FAMILY_ID      VARCHAR2(32) NOT NULL,
    AUTH_METHOD    VARCHAR2(30),
    CREATED_AT     TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    EXPIRES_AT     TIMESTAMP NOT NULL,
    USED_AT        TIMESTAMP,
    REVOKED_AT     TIMESTAMP,
    REVOKE_REASON  VARCHAR2(30),
    CONSTRAINT UQ_CARD_REFRESH_TOKENS_HASH UNIQUE (TOKEN_HASH)
);

CREATE INDEX IX_CARD_REFRESH_TOKENS_FAMILY ON CARD_REFRESH_TOKENS (FAMILY_ID);
CREATE INDEX IX_CARD_REFRESH_TOKENS_USER ON CARD_REFRESH_TOKENS (USER_ID, REVOKED_AT);

-- Password reset links: hashed, single use, short expiry
CREATE TABLE CARD_PASSWORD_RESETS (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID     NUMBER NOT NULL CONSTRAINT FK_CARD_PASSWORD_RESETS_USER REFERENCES CARD_USERS (ID),
    TOKEN_HASH  VARCHAR2(64) NOT NULL,
    CREATED_AT  TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    EXPIRES_AT  TIMESTAMP NOT NULL,
    USED_AT     TIMESTAMP,
    CONSTRAINT UQ_CARD_PASSWORD_RESETS_HASH UNIQUE (TOKEN_HASH)
);

CREATE INDEX IX_CARD_PASSWORD_RESETS_USER ON CARD_PASSWORD_RESETS (USER_ID, USED_AT);

-- Browser sign-in brokered by the API (Google web flow, eBay, OIDC SSO). /start creates a row
-- keyed by the OAuth state; /callback finishes the provider exchange, sets USER_ID and a
-- one-time CODE that goes back to the app in the deep link; /complete swaps that code (plus
-- the app's PKCE verifier) for tokens. Tokens never appear in a URL.
CREATE TABLE CARD_AUTH_FLOWS (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STATE_HASH          VARCHAR2(64) NOT NULL,
    PROVIDER            VARCHAR2(30) NOT NULL,
    APP_REDIRECT_URI    VARCHAR2(1000) NOT NULL,
    APP_CODE_CHALLENGE  VARCHAR2(128) NOT NULL,
    PROVIDER_VERIFIER   VARCHAR2(128),
    NONCE               VARCHAR2(64),
    CREATED_AT          TIMESTAMP DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    EXPIRES_AT          TIMESTAMP NOT NULL,
    CALLBACK_AT         TIMESTAMP,
    USER_ID             NUMBER CONSTRAINT FK_CARD_AUTH_FLOWS_USER REFERENCES CARD_USERS (ID),
    CODE_HASH           VARCHAR2(64),
    CODE_EXPIRES_AT     TIMESTAMP,
    CODE_USED_AT        TIMESTAMP,
    CONSTRAINT UQ_CARD_AUTH_FLOWS_STATE UNIQUE (STATE_HASH),
    CONSTRAINT UQ_CARD_AUTH_FLOWS_CODE UNIQUE (CODE_HASH)
);

CREATE INDEX IX_CARD_AUTH_FLOWS_USER ON CARD_AUTH_FLOWS (USER_ID);
