-- AI usage metering: one row per Claude call (card identify, lot analysis), with the
-- tokens it billed and what that cost us. Drives the free plan's monthly AI cap
-- (GET /api/usage, HTTP 402 USAGE_LIMIT) and the Pro abuse guard.
-- CREATED_AT is written by the app in UTC (months reset on the 1st, 00:00 UTC).
CREATE TABLE CARD_AI_USAGE (
    ID                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID               NUMBER NOT NULL CONSTRAINT FK_CARD_AI_USAGE_USER REFERENCES CARD_USERS (ID),
    CREATED_AT            TIMESTAMP NOT NULL,
    FEATURE               VARCHAR2(30) NOT NULL,
    MODEL                 VARCHAR2(80) NOT NULL,
    INPUT_TOKENS          NUMBER(12) DEFAULT 0 NOT NULL,
    OUTPUT_TOKENS         NUMBER(12) DEFAULT 0 NOT NULL,
    CACHE_WRITE_TOKENS    NUMBER(12) DEFAULT 0 NOT NULL,
    CACHE_READ_TOKENS     NUMBER(12) DEFAULT 0 NOT NULL,
    COST_USD              NUMBER(12,6) NOT NULL,
    PLAN                  VARCHAR2(10) NOT NULL,
    SUCCEEDED             CHAR(1) DEFAULT 'Y' NOT NULL CHECK (SUCCEEDED IN ('Y', 'N'))
);

CREATE INDEX IX_CARD_AI_USAGE_USER ON CARD_AI_USAGE (USER_ID, CREATED_AT);

-- One row per user, month and alert kind (e.g. WARN_80), so each warning push goes out once a month
CREATE TABLE CARD_USAGE_ALERTS (
    USER_ID     NUMBER NOT NULL CONSTRAINT FK_CARD_USAGE_ALERTS_USER REFERENCES CARD_USERS (ID),
    MONTH_START DATE NOT NULL,
    ALERT_KIND  VARCHAR2(20) NOT NULL,
    SENT_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CARD_USAGE_ALERTS PRIMARY KEY (USER_ID, MONTH_START, ALERT_KIND)
);
